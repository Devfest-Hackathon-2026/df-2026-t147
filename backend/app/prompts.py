"""Gemini へのプロンプト。個人を特定する情報は渡さず、ニックネームと数値のみ。"""
import json

_RULES_COMMON = """あなたは子どもの生活習慣を応援する親子向けアプリの文章担当です。
守ること:
- 断定しない。子どもの性格・能力・将来を決めつけない。診断や評価をしない。
- ネガティブな推測をしない。できていない点を責めない。
- 与えられた事実（数字）だけを使い、書かれていない事実を作らない。
- 出力は指定のJSONのみ。説明文やコードブロックは不要。"""


_AXIS_MEANING = {
    "feeling": "はみがきの きもち（選択肢: 0=たのしい・いいきもち / 1=ふつう / 2=いやな きもち）",
    "self": "じぶんから はじめたか（選択肢: 0=じぶんから / 1=すこし / 2=いわれて）",
    "difficulty": "はみがきの むずかしさ（選択肢: 0=かんたん / 1=ふつう / 2=むずかしい）",
}


def questions_prompt(facts: dict, base: list[dict], prev_texts: list[str]) -> str:
    """facts: 事実のみ（連続日数・自分から連続・直近7日の軸ごとの回答件数・さぼり）。子の名前は渡さない。"""
    return f"""{_RULES_COMMON}

きょう子どもに聞く、はみがきの質問を3つ（軸ごとに1問）つくってください。
- 軸の内容は変えない。その日の事実に合わせて、言い方だけを近づける。
{json.dumps(_AXIS_MEANING, ensure_ascii=False)}
- 事実（ルールで算出済み）: {json.dumps(facts, ensure_ascii=False)}
- 質問文: ひらがな中心（漢字は使わない）、20文字以内、必ず「みがく」か「はみがき」の話にする。
- 質問文と選択肢は、単語や言葉のまとまりごとに、全角スペースではなく半角スペースを入れる（例: きょうの はみがき、きもちは どうだった？）。改行は入れない。
- 選択肢はちょうど3つ、各10文字以内。並びは固定: 0番目が前向き、1番目がふつう、2番目が後ろ向き。意味と順序は変えない。
- 責める・決めつける・ほかの子や前の日と比べる言い方、診断や評価に聞こえる言葉は使わない。「なんで」「どうして」「ちゃんと」「いつも」も使わない。
- 前の日の質問と同じ言い回しは避ける: {json.dumps(prev_texts, ensure_ascii=False)}
- 参考にする基本の質問: {json.dumps(base, ensure_ascii=False)}

出力形式: {{"questions":[{{"axis":"feeling","text":"...","choices":["...","...","..."]}},{{"axis":"self",...}},{{"axis":"difficulty",...}}]}}"""


def praise_trend_prompt(facts: list[str]) -> str:
    return f"""{_RULES_COMMON}

親が子どもをほめる手がかりとして、次の事実の一覧から「傾向の一文」を1つだけ書いてください。
- 事実（ルールで算出済み）: {json.dumps(facts, ensure_ascii=False)}
- 事実にない数字や出来事は書かない。子どもの名前は書かない。
- 「〜な様子が見られます」のように、断定しない形で終える（末尾は「見られます」か「ようです」）。
- 1文だけ。40文字程度まで（長くても60文字以内）。
- 「いつも」「ちゃんと」「なんで」など、決めつけや責める言い方は使わない。

出力形式: {{"text":"..."}}"""


def phrases_prompt(nickname: str, facts: list[str]) -> str:
    return f"""{_RULES_COMMON}

親が子どもに声をかける文を3案つくってください。
- 子どもの呼び名: {nickname}
- 事実（ルールで算出済み）: {json.dumps(facts, ensure_ascii=False)}
- 「えらい子」など人への評価ではなく、行動（続けた・自分から始めた）を認める文にする。
- 各40文字以内、口に出して言いやすい話し言葉。3案は切り口を変える（事実を伝える／うれしい気持ちを伝える／次を急かさない励まし）。

出力形式: {{"phrases":["...","...","..."]}}"""


def trend_prompt(nickname: str, w: dict) -> str:
    data = {
        "できた日数": w["doneDays"], "自分から始めた日数": w["selfDays"], "最長の連続日数": w["longestStreak"],
        "先週の自分から日数": w["prevSelfDays"], "回答数": w["answerCount"],
        "回答の集計(軸:[前向き,ふつう,大変]の回数)": w["answerCounts"],
    }
    return f"""{_RULES_COMMON}

親向けに、今週の様子を2〜3文でまとめてください。
- 子どもの呼び名: {nickname}
- 集計値: {json.dumps(data, ensure_ascii=False)}
- 「〜な傾向が見られます」「〜の日もありました」のように、断定を避けた表現にする。
- 「この子は〜な子です」とは書かない。解釈は親に委ねる。140文字以内。

出力形式: {{"text":"..."}}"""
